import pandas as pd

# 1. Load the dataset
df = pd.read_csv("churnguard_data.csv")

# 2. Drop customerID column
df = df.drop("customerID", axis=1)

# 3. Remove duplicate rows
df = df.drop_duplicates()

# 4. Strip whitespace from gender and PaymentMethod
df["gender"] = df["gender"].str.strip()
df["PaymentMethod"] = df["PaymentMethod"].str.strip()

# 5. Standardise Churn, PhoneService and PaperlessBilling
df["Churn"] = df["Churn"].str.strip().str.title()
df["PhoneService"] = df["PhoneService"].str.strip().str.title()
df["PaperlessBilling"] = df["PaperlessBilling"].str.strip().str.title()

# 6. Fix Contract values
contract_map = {
    "Monthly": "Month-to-month",
    "month to month": "Month-to-month",
    "month-to-month": "Month-to-month",
    "Month-to-month": "Month-to-month",

    "1 year": "One year",
    "One year": "One year",
    "One Year": "One year",
    "one year": "One year",

    "2 year": "Two year",
    "Two year": "Two year",
    "Two Year": "Two year",
    "two year": "Two year"
}

df["Contract"] = df["Contract"].replace(contract_map)

# 7. Fix InternetService values
internet_map = {
    "dsl": "DSL",
    "DSl": "DSL",
    "DSL": "DSL",

    "Fibre optic": "Fiber optic",
    "Fiber optic": "Fiber optic",
    "FiberOptic": "Fiber optic",
    "fiber optic": "Fiber optic",

    "None": "No",
    "none": "No",
    "No": "No"
}

df["InternetService"] = df["InternetService"].replace(internet_map)

# Fill missing InternetService values with "No"
df["InternetService"] = df["InternetService"].fillna("No")

# 8. Convert TotalCharges to numeric
df["TotalCharges"] = pd.to_numeric(
    df["TotalCharges"],
    errors="coerce"
)

# 9. Remove rows where tenure is zero or negative
df = df[df["tenure"] > 0]

# 10. Remove rows where MonthlyCharges is less than 10 or greater than 200
df = df[
    (df["MonthlyCharges"] >= 10) &
    (df["MonthlyCharges"] <= 200)
]

# 11. Fill missing values

# Fill MonthlyCharges with column mean
df["MonthlyCharges"] = df["MonthlyCharges"].fillna(
    df["MonthlyCharges"].mean()
)

# Fill TotalCharges with column mean
df["TotalCharges"] = df["TotalCharges"].fillna(
    df["TotalCharges"].mean()
)

# Fill tenure with column median and round to integer
df["tenure"] = df["tenure"].fillna(
    round(df["tenure"].median())
)

# 12. Print cleaned DataFrame shape
print("Shape of cleaned DataFrame:", df.shape)

# 13. Print missing value counts
print("\nMissing values after cleaning:")
print(df.isnull().sum())