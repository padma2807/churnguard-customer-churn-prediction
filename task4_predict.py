import pandas as pd
from sklearn.linear_model import LogisticRegression

# Load the dataset

df = pd.read_csv("churnguard_data.csv")

# Drop customerID

df = df.drop("customerID", axis=1)

# Remove duplicate rows

df = df.drop_duplicates()

# Strip whitespace

df["gender"] = df["gender"].str.strip()
df["PaymentMethod"] = df["PaymentMethod"].str.strip()

# Standardise values

df["Churn"] = df["Churn"].str.strip().str.title()
df["PhoneService"] = df["PhoneService"].str.strip().str.title()
df["PaperlessBilling"] = df["PaperlessBilling"].str.strip().str.title()

# Fix Contract values

contract_map = {
"Monthly": "Month-to-month",
"month to month": "Month-to-month",
"month-to-month": "Month-to-month",
"Month-to-month": "Month-to-month",
"1 year": "One year",
"One year": "One year",
"One Year": "One year",
"one year": "One year",
"2 year": "Two year",
"Two year": "Two year",
"Two Year": "Two year",
"two year": "Two year"
}

df["Contract"] = df["Contract"].replace(contract_map)

# Fix InternetService values

internet_map = {
"dsl": "DSL",
"DSl": "DSL",
"DSL": "DSL",
"Fibre optic": "Fiber optic",
"Fiber optic": "Fiber optic",
"FiberOptic": "Fiber optic",
"fiber optic": "Fiber optic",
"None": "No",
"none": "No",
"No": "No"
}

df["InternetService"] = df["InternetService"].replace(internet_map)
df["InternetService"] = df["InternetService"].fillna("No")

# Convert TotalCharges to numeric

df["TotalCharges"] = pd.to_numeric(
df["TotalCharges"],
errors="coerce"
)

# Remove invalid tenure values

df = df[df["tenure"] > 0]

# Remove invalid MonthlyCharges values

df = df[
(df["MonthlyCharges"] >= 10) &
(df["MonthlyCharges"] <= 200)
]

# Fill missing values

df["MonthlyCharges"] = df["MonthlyCharges"].fillna(
df["MonthlyCharges"].mean()
)

df["TotalCharges"] = df["TotalCharges"].fillna(
df["TotalCharges"].mean()
)

df["tenure"] = df["tenure"].fillna(
round(df["tenure"].median())
)

# Encode Churn

df["Churn"] = df["Churn"].map({
"Yes": 1,
"No": 0
})

# Encode Contract

contract_encoding = {
"Month-to-month": 0,
"One year": 1,
"Two year": 2
}

df["Contract"] = df["Contract"].map(contract_encoding)

# Use only the five required features

features = [
"tenure",
"MonthlyCharges",
"TotalCharges",
"SeniorCitizen",
"Contract"
]

X = df[features]
y = df["Churn"]

# Train model on the full cleaned dataset

model = LogisticRegression(max_iter=1000)
model.fit(X, y)

# Get customer input

tenure = int(input("Enter tenure (months):"))
monthly_charges = float(input("Enter Monthly Charges:"))
total_charges = float(input("Enter Total Charges:"))
senior_citizen = int(input("Senior Citizen? (1 = Yes, 0 = No):"))
contract = int(input(
"Contract type (0 = Month-to-month, 1 = One year, 2 = Two year):"
))

# Create prediction input

customer = pd.DataFrame([[
tenure,
monthly_charges,
total_charges,
senior_citizen,
contract
]], columns=features)

# Make prediction

prediction = model.predict(customer)[0]

# Print result

if prediction == 1:
  print("Prediction: This customer is likely to CHURN.")
else:
  print("Prediction: This customer is likely to STAY.")